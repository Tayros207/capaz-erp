-- Miembros de la empresa ACTUAL (la de la transacción), sin exponer contraseñas ni sesiones. Es
-- una vista normal del dueño (sin security_invoker): `capaz_app` solo ve lo que la vista filtra.
create or replace view core.v_miembros as
  select m.organization_id as tenant_id, m.user_id as usuario_id, u.name as nombre, u.email as correo, m.role as rol, m.created_at as miembro_desde
    from auth.member m
    join auth."user" u on u.id = m.user_id
   where m.organization_id = nullif(current_setting('app.tenant_id', true), '');
--> statement-breakpoint
grant select on core.v_miembros to capaz_app;
